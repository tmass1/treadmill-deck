#!/bin/bash
# Build C1250 Deck (on-console app) into c1250-deck.apk.
# Needs: JDK 11+, Android SDK (platforms/android-33, build-tools/35.0.0), OkHttp/Okio jars in lib/.
set -euo pipefail

APP="$(cd "$(dirname "$0")" && pwd)"
SDK="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-$HOME/Library/Android/sdk}}"
BT="$SDK/build-tools/35.0.0"
PLATFORM="$SDK/platforms/android-33/android.jar"
PAGE="${PAGE:-$APP/../c1250-deck.html}"
B="$APP/build"
# Private things (the signing key, the site key) live outside this repo, by default in
# ../treadmill-deck-private next to it: secrets.env (DECK_KEY, DECK_SITE, KS_PASS) and
# keystore/c1250deck.jks. See README.md.
PRIV="${DECK_PRIVATE:-$APP/../../treadmill-deck-private}"
if [ -f "$PRIV/secrets.env" ]; then set -a; . "$PRIV/secrets.env"; set +a; fi
DECK_KEY="${DECK_KEY:-}"
DECK_SITE="${DECK_SITE:-https://treadmill-deck.tommymassaro.com}"
KS="${DECK_KEYSTORE:-$PRIV/keystore/c1250deck.jks}"
KS_PASS="${KS_PASS:-c1250deck}"
LIBS="$APP/lib/okhttp-3.14.9.jar:$APP/lib/okio-1.17.6.jar"

rm -rf "$B" && mkdir -p "$B/gen" "$B/obj" "$B/dex" "$B/pkg"
rm -f "$APP/c1250-deck.apk"
mkdir -p "$APP/assets/www"

echo "== page"
python3 - "$PAGE" "$APP/assets/www/index.html" <<'PY'
import re, sys
src = open(sys.argv[1]).read()
head = ('<!doctype html><html lang="en"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">'
        '<style>:root{color-scheme:light}body{margin:0;font:14px system-ui}[hidden]{display:none!important}img{max-width:100%}</style>')
# The app container may carry extra attributes (id, data-*), so match the tag start.
m = re.search(r'<div class="app"[\s>]', src)
if not m: sys.exit('build.sh: no <div class="app"> container found in ' + sys.argv[1])
i = m.start()
open(sys.argv[2], 'w').write(head + src[:i] + '</head><body>' + src[i:] + '</body></html>')
PY

# Home background photos (see bg/CREDITS.md) ride along next to the page.
rm -rf "$APP/assets/www/bg" && mkdir -p "$APP/assets/www/bg" && cp "$APP"/../bg/*.webp "$APP/assets/www/bg/"

echo "== resources"
"$BT/aapt2" compile --dir "$APP/res" -o "$B/res.zip"
"$BT/aapt2" link -o "$B/base.apk" -I "$PLATFORM" --manifest "$APP/AndroidManifest.xml" \
  --debug-mode --java "$B/gen" -A "$APP/assets" "$B/res.zip"

echo "== secrets"
[ -n "$DECK_KEY" ] || echo "   no DECK_KEY: run uploads, reports and updates from the site are off in this build"
cat > "$B/gen/Secrets.java" <<JAVA
package com.massaro.c1250deck;
/** Generated by build.sh from secrets.env; never committed. */
final class Secrets {
    static final String DECK_KEY = "$DECK_KEY";
    static final String SITE = "$DECK_SITE";
}
JAVA

echo "== java"
find "$APP/src" "$B/gen" -name '*.java' > "$B/sources.txt"
javac -nowarn --release 11 -classpath "$PLATFORM:$LIBS" -d "$B/obj" @"$B/sources.txt" 2>&1 | grep -v '^Picked up' || true
[ -f "$B/obj/com/massaro/c1250deck/MainActivity.class" ] || { echo "javac failed"; exit 1; }

echo "== dex (R8 shrink)"
java -cp "$BT/lib/d8.jar" com.android.tools.r8.R8 --release --min-api 26 --lib "$PLATFORM" \
  --pg-conf "$APP/proguard.pro" --output "$B/dex" \
  $(find "$B/obj" -name '*.class') "$APP/lib/okhttp-3.14.9.jar" "$APP/lib/okio-1.17.6.jar" 2>&1 | grep -v '^Picked up' || true
[ -f "$B/dex/classes.dex" ] || { echo "dex failed"; exit 1; }

echo "== package"
cp "$B/base.apk" "$B/unsigned.apk"
(cd "$B/dex" && zip -q "$B/unsigned.apk" classes*.dex)
"$BT/zipalign" -f -p 4 "$B/unsigned.apk" "$B/aligned.apk"

if [ ! -f "$KS" ]; then
  echo "   no signing key at $KS: making a new one (a console running another key's build can't update to this one)"
  mkdir -p "$(dirname "$KS")"
  keytool -genkeypair -keystore "$KS" -storepass "$KS_PASS" -keypass "$KS_PASS" -alias deck \
    -keyalg RSA -keysize 2048 -validity 10000 -dname "CN=C1250 Deck" 2>&1 | grep -v '^Picked up' || true
fi
"$BT/apksigner" sign --ks "$KS" --ks-pass "pass:$KS_PASS" --key-pass "pass:$KS_PASS" --ks-key-alias deck \
  --out "$APP/c1250-deck.apk" "$B/aligned.apk" 2>&1 | grep -v '^Picked up' || true
"$BT/apksigner" verify "$APP/c1250-deck.apk" 2>&1 | grep -v '^Picked up' || true
ls -la "$APP/c1250-deck.apk"
